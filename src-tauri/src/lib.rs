pub mod adb;
mod commands;
pub mod device;
pub mod error;
pub mod localfs;
pub mod mirror;
mod notifications;
mod state;
mod tray;

#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    tauri::Builder::default()
        .plugin(tauri_plugin_process::init())
        .plugin(tauri_plugin_updater::Builder::new().build())
        .plugin(tauri_plugin_opener::init())
        .plugin(tauri_plugin_dialog::init())
        .plugin(tauri_plugin_notification::init())
        .manage(state::AppState::default())
        .manage(commands::files::FilesState::default())
        .manage(commands::logcat::LogcatSessions::default())
        .manage(commands::overview::OverviewState::default())
        .manage(commands::bugreport::BugreportState::default())
        .manage(commands::shell::ShellSessions::default())
        .manage(commands::perf::PerfSubscriptions::default())
        .manage(commands::connection::ConnectionState::default())
        .manage(commands::apps::AppsState::default())
        .manage(mirror::MirrorState::default())
        .manage(tray::TrayState::default())
        .setup(|app| {
            notifications::setup(app.handle());
            Ok(())
        })
        .on_window_event(tray::on_window_event)
        .invoke_handler(tauri::generate_handler![
            commands::adb::locate_adb,
            commands::adb::install_platform_tools,
            commands::adb::cancel_platform_tools_install,
            commands::devices::watch_devices,
            commands::devices::device_info,
            commands::files::files_list,
            commands::files::files_mkdir,
            commands::files::files_rename,
            commands::files::files_delete,
            commands::files::files_chmod,
            commands::files::files_storage,
            commands::files::files_preview,
            commands::files::files_default_download_dir,
            commands::files::files_local_summary,
            commands::files::files_pull,
            commands::files::files_push,
            commands::files::files_transfer_control,
            commands::files::files_local_list,
            commands::files::files_local_resolve,
            commands::files::files_local_places,
            commands::files::files_drag_stage,
            commands::files::files_start_drag,
            commands::logcat::logcat_start,
            commands::logcat::logcat_stop,
            commands::logcat::logcat_clear,
            commands::logcat::logcat_packages,
            commands::logcat::logcat_package_processes,
            commands::logcat::logcat_export,
            commands::overview::device_snapshot,
            commands::overview::reboot_device,
            commands::overview::take_screenshot,
            commands::overview::start_recording,
            commands::overview::stop_recording,
            commands::overview::recording_status,
            commands::gallery::list_captures,
            commands::gallery::delete_capture,
            commands::dev_settings::read_dev_settings,
            commands::dev_settings::apply_dev_setting,
            commands::bugreport::create_bugreport,
            commands::bugreport::cancel_bugreport,
            commands::bugreport::list_bugreports,
            commands::bugreport::delete_bugreport,
            commands::shell::shell_open,
            commands::shell::shell_write,
            commands::shell::shell_resize,
            commands::shell::shell_close,
            commands::shell::shell_exec,
            commands::ports::ports_list,
            commands::ports::ports_add,
            commands::ports::ports_remove,
            commands::ports::ports_remove_all,
            commands::ports::ports_free_host_port,
            commands::intents::intent_send,
            commands::intents::intent_command,
            commands::intents::input_text,
            commands::intents::input_key,
            commands::perf::perf_subscribe,
            commands::perf::perf_unsubscribe,
            commands::perf::perf_processes,
            commands::perf::perf_kill,
            commands::perf::perf_export_csv,
            commands::adb::adb_scan,
            commands::adb::adb_use_path,
            commands::adb::adb_key_fingerprint,
            commands::adb::adb_server_status,
            commands::adb::adb_ensure_server,
            commands::adb::adb_restart_server,
            commands::connection::wifi_mdns_services,
            commands::connection::wifi_qr_session,
            commands::connection::wifi_pair,
            commands::connection::wifi_cancel_pair,
            commands::connection::wifi_connect,
            commands::connection::wifi_disconnect,
            commands::connection::wifi_tcpip,
            commands::connection::device_wifi_ip,
            commands::connection::devices_reconnect,
            commands::connection::devices_reconnect_offline,
            commands::connection::devices_summary,
            commands::connection::avd_list,
            commands::connection::avd_launch,
            commands::connection::devices_exec,
            commands::connection::devices_screenshot,
            commands::diagnostics::diagnostics_run,
            commands::apps::list_apps,
            commands::apps::app_details,
            commands::apps::app_components,
            commands::apps::app_storage,
            commands::apps::app_ops,
            commands::apps::app_battery,
            commands::apps::load_app_meta,
            commands::apps::launch_app,
            commands::apps::start_activity,
            commands::apps::force_stop_app,
            commands::apps::clear_app_data,
            commands::apps::set_app_enabled,
            commands::apps::uninstall_app,
            commands::apps::install_existing_app,
            commands::apps::set_app_permission,
            commands::apps::reset_app_permissions,
            commands::apps::set_app_op,
            commands::apps::set_standby_bucket,
            commands::apps::set_battery_unrestricted,
            commands::apps::inspect_package_file,
            commands::apps::installed_version,
            commands::apps::install_package,
            commands::apps::cancel_apps_job,
            commands::apps::extract_apks,
            commands::mirror::mirror_start,
            commands::mirror::mirror_stop,
            commands::mirror::mirror_control,
            commands::tray::tray_sync,
            commands::tray::tray_watch,
        ])
        .build(tauri::generate_context!())
        .expect("error while building tauri application")
        .run(tray::on_run_event);
}
